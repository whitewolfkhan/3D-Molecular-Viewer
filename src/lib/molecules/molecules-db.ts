export type MoleculeCategory = 
  | 'organic'
  | 'inorganic'
  | 'biochemical'
  | 'pharmaceutical'
  | 'polymer'
  | 'metal-complex'
  | 'acid'
  | 'base'
  | 'solvent'
  | 'fuel';

export type MoleculeProperty = 
  | 'polar'
  | 'non-polar'
  | 'aromatic'
  | 'hydrophobic'
  | 'hydrophilic'
  | 'volatile'
  | 'toxic'
  | 'flammable';

export interface ExtendedMolecule extends Molecule {
  category: MoleculeCategory;
  properties: MoleculeProperty[];
  molarMass: number;
  meltingPoint?: number;
  boilingPoint?: number;
  density?: number;
}

// Helper function to create atoms
function createAtom(id: string, element: string, position: [number, number, number]): Atom {
  return { id, element, position };
}

// Helper function to create bonds
function createBond(id: string, atom1Id: string, atom2Id: string, type: 'single' | 'double' | 'triple', length?: number): Bond {
  return { id, atom1Id, atom2Id, type, length };
}

