// Helper functions for searching and filtering
export function getMoleculesByCategory(category: MoleculeCategory): ExtendedMolecule[] {
  return MOLECULES_DB.filter(m => m.category === category);
}

export function getMoleculesByProperty(property: MoleculeProperty): ExtendedMolecule[] {
  return MOLECULES_DB.filter(m => m.properties.includes(property));
}

export function searchMolecules(query: string): ExtendedMolecule[] {
  const lowerQuery = query.toLowerCase();
  return MOLECULES_DB.filter(m => 
    m.name.toLowerCase().includes(lowerQuery) ||
    m.formula.toLowerCase().includes(lowerQuery) ||
    m.description.toLowerCase().includes(lowerQuery)
  );
}

export function getMoleculeById(id: string): ExtendedMolecule | undefined {
  return MOLECULES_DB.find(m => m.id === id);
}

export function getAllCategories(): MoleculeCategory[] {
  return ['organic', 'inorganic', 'biochemical', 'pharmaceutical', 'polymer', 'acid', 'base', 'solvent', 'fuel'];
}

export function getAllProperties(): MoleculeProperty[] {
  return ['polar', 'non-polar', 'aromatic', 'hydrophobic', 'hydrophilic', 'volatile', 'toxic', 'flammable'];
}
